"""Mode D — machine-learning surrogate.

Tree-ensemble regressors learn the aerodynamic coefficients from

    geometry parameters + air density + relative air speed  ->  Cd, Cl, Cl_front

using results generated by another engine (Mode A or Mode B today; CFD results
can be added to the dataset later). Two algorithms are fitted to the same
training split — a random forest and gradient boosting — and the one with the
lower error on held-out data is used for prediction; the metrics of both are
stored. Drag and downforce are then computed from the predicted coefficients
with the usual force equations.

The surrogate interpolates its training data. It is never more accurate than
the engine that produced the data, and it is not a physical model: every result
it returns is labelled as a prediction and carries its validation metrics.
"""

