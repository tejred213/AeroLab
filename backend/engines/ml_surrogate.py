DATA_DIR = Path(__file__).resolve().parents[1] / "data"
DATASET_DIR = DATA_DIR / "datasets"
MODEL_DIR = DATA_DIR / "surrogates"

TARGETS = ["cd", "cl", "clFront"]
SPEED_RANGE = (10.0, 75.0)
DENSITY_RANGE = (1.0, 1.32)
ALGORITHMS = {
    "random-forest": "Random forest (200 trees)",
    "gradient-boosting": "Gradient boosting (400 trees, depth 3)",
}

SURROGATE_ASSUMPTIONS = [
    "Coefficients are predicted by a regression model fitted to simulated data; no physics is solved at prediction time.",
    "The prediction inherits every assumption and error of the engine that generated the training data.",
    "Trained at zero yaw: crosswind effects are not included in the prediction.",
    "Predictions are reliable only inside the sampled parameter ranges; outside them tree ensembles extrapolate as a constant.",
    "The stated uncertainty combines the held-out validation error, the disagreement between the two fitted algorithms at this point, and the error floor of the source model.",
    "Drag and downforce are computed from the predicted coefficients with F = q C A, using the frontal area of the actual geometry.",
    "Separation location and base pressure shown in AeroLab are empirical estimates, not predicted by the surrogate.",
]


@dataclass
class TrainedSurrogate:
    meta: dict[str, Any]
    #: Every fitted algorithm, keyed as in ALGORITHMS; meta["selected"] names the one used for prediction.
    models: dict[str, Any]

    @property
    def selected(self) -> Any:
        return self.models[self.meta["selected"]]


def _new_model(key: str, seed: int) -> Any:
    if key == "random-forest":
        return RandomForestRegressor(n_estimators=200, min_samples_leaf=2, random_state=seed, n_jobs=-1)
    return MultiOutputRegressor(
        GradientBoostingRegressor(n_estimators=400, max_depth=3, learning_rate=0.05, subsample=0.8, random_state=seed)
    )


_lock = threading.Lock()
_loaded: dict[str, TrainedSurrogate] = {}


def _feature_names(parameters: list[str]) -> list[str]:
    return [*parameters, "airDensity", "relativeSpeed"]


def list_models() -> list[dict[str, Any]]:
    """Metadata of every stored surrogate, newest first."""
    if not MODEL_DIR.exists():
        return []
    models = []
    for path in MODEL_DIR.glob("*.json"):
        try:
            models.append(json.loads(path.read_text(encoding="utf-8")))
        except (json.JSONDecodeError, OSError):
            continue
    return sorted(models, key=lambda meta: meta["createdAt"], reverse=True)


def _load(model_id: str) -> TrainedSurrogate:
    with _lock:
        cached = _loaded.get(model_id)
    if cached is not None:
        return cached
    meta = json.loads((MODEL_DIR / f"{model_id}.json").read_text(encoding="utf-8"))
    stored = joblib.load(MODEL_DIR / f"{model_id}.joblib")
    if not isinstance(stored, dict):
        # Stored before two algorithms were compared: a single random forest.
        stored = {"random-forest": stored}
        meta.setdefault("selected", "random-forest")
    surrogate = TrainedSurrogate(meta=meta, models=stored)
    with _lock:
        _loaded[model_id] = surrogate
    return surrogate


def latest_model_for(vehicle_id: str) -> TrainedSurrogate | None:
    for meta in list_models():
        if meta["vehicleId"] == vehicle_id:
            return _load(meta["modelId"])
    return None


def generate_dataset(
    request: dict[str, Any],
    source_engine: SimulationEngine,
    report: ProgressReporter = no_progress,
) -> tuple[pd.DataFrame, dict[str, tuple[float, float]]]:
    """Latin-hypercube sample of the design space, evaluated with the source engine."""
    config = request["config"]
    parameters = request["parameters"]
    base = config["geometry"]
    bounds: dict[str, tuple[float, float]] = {}
    for param in parameters:
        definition = PARAM_BY_ID[param]
        half = 0.5 * request["spread"] * (definition["max"] - definition["min"])
        bounds[param] = (max(definition["min"], base[param] - half), min(definition["max"], base[param] + half))

    names = _feature_names(parameters)
    lows = np.array([bounds[p][0] for p in parameters] + [DENSITY_RANGE[0], SPEED_RANGE[0]])
    highs = np.array([bounds[p][1] for p in parameters] + [DENSITY_RANGE[1], SPEED_RANGE[1]])
    sampler = qmc.LatinHypercube(d=len(names), seed=request["seed"])
    # Oversample: some combinations are not buildable geometries and are skipped.
    points = qmc.scale(sampler.random(int(request["samples"] * 1.6) + 20), lows, highs)

    rows: list[dict[str, float]] = []
    wanted = request["samples"]
    for index, point in enumerate(points):
        if len(rows) >= wanted:
            break
        geometry = {**base, **{param: float(value) for param, value in zip(parameters, point[: len(parameters)])}}
        if not is_geometry_valid(geometry):
            continue
        sample_config = {
            **config,
            "mode": source_engine.mode,
            "fidelity": "coarse",
            "geometry": geometry,
            "speed": float(point[-1]),
            "environment": {
                **config["environment"],
                "airDensityMode": "direct",
                "airDensity": float(point[-2]),
                "windSpeed": 0.0,
                "windAngle": 0.0,
            },
        }
        try:
            result = source_engine.simulate(sample_config)
        except SimulationError:
            continue
        coefficients = result["coefficients"]
        rows.append(
            {
                **{param: geometry[param] for param in parameters},
                "airDensity": float(point[-2]),
                "relativeSpeed": float(point[-1]),
                "cd": coefficients["cd"],
                "cl": coefficients["cl"],
                "clFront": coefficients["clFront"],
                # Recorded for inspection of the dataset; computed from the predicted coefficients at inference.
                "drag": result["forces"]["drag"],
                "downforce": result["forces"]["downforce"],
            }
        )
        report("SOLVING", 0.85 * len(rows) / wanted, f"Generating training data · {len(rows)} / {wanted} samples")
        if index > 20 and len(rows) == 0:
            break

    if len(rows) < max(30, wanted // 4):
        raise SimulationError(
            "SURROGATE_DATASET_TOO_SMALL",
            f"Only {len(rows)} valid samples could be generated; the surrogate was not trained. "
            "Reduce the parameter spread or start from a different base geometry.",
        )
    return pd.DataFrame(rows), bounds


def train(request: dict[str, Any], source_engine: SimulationEngine, report: ProgressReporter = no_progress) -> dict[str, Any]:
    """Generates the dataset, fits the model, evaluates it on held-out data and stores it."""
    report("PREPARING", 0.0, "Sampling the design space")
    prepare_case(request["config"])  # validates the base configuration
    frame, bounds = generate_dataset(request, source_engine, report)
    names = _feature_names(request["parameters"])

    report("POST_PROCESSING", 0.88, "Fitting and validating the regressors")
    features = frame[names].to_numpy()
    targets = frame[TARGETS].to_numpy()
    seed = request["seed"]
    x_train, x_valid, y_train, y_valid = train_test_split(features, targets, test_size=0.2, random_state=seed)

    # Fit every algorithm on the same split and score it on the held-out part.
    candidates: list[dict[str, Any]] = []
    for key, label in ALGORITHMS.items():
        predicted = _new_model(key, seed).fit(x_train, y_train).predict(x_valid)
        candidates.append(
            {
                "key": key,
                "algorithm": label,
                "validationRmseCd": float(math.sqrt(mean_squared_error(y_valid[:, 0], predicted[:, 0]))),
                "validationRmseCl": float(math.sqrt(mean_squared_error(y_valid[:, 1], predicted[:, 1]))),
                "validationR2Cd": float(r2_score(y_valid[:, 0], predicted[:, 0])),
                "validationR2Cl": float(r2_score(y_valid[:, 1], predicted[:, 1])),
            }
        )
    best = max(candidates, key=lambda candidate: candidate["validationR2Cd"] + candidate["validationR2Cl"])
    for candidate in candidates:
        candidate["selected"] = candidate is best

    report("POST_PROCESSING", 0.94, "Refitting on all samples")
    # Refit on all data for use; the validation metrics above come from the held-out split.
    models = {key: _new_model(key, seed).fit(features, targets) for key in ALGORITHMS}

    started = time.perf_counter()
    repeats = 20
    for _ in range(repeats):
        models[best["key"]].predict(features[:1])
    inference_ms = (time.perf_counter() - started) / repeats * 1000

    model_id = hash_value({"request": request, "time": time.time()})[:16]
    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    frame.to_csv(DATASET_DIR / f"{model_id}.csv", index=False)
    joblib.dump(models, MODEL_DIR / f"{model_id}.joblib")

    meta = {
        "modelId": model_id,
        "algorithm": best["algorithm"],
        "selected": best["key"],
        "candidates": candidates,
        "createdAt": datetime.now(timezone.utc).isoformat(),
        "vehicleId": request["config"]["vehicleId"],
        "sourceMode": source_engine.mode,
        "trainingSamples": int(len(frame)),
        "validationSamples": int(len(x_valid)),
        "validationRmseCd": best["validationRmseCd"],
        "validationRmseCl": best["validationRmseCl"],
        "validationR2Cd": best["validationR2Cd"],
        "validationR2Cl": best["validationR2Cl"],
        "inferenceTimeMs": inference_ms,
        "parameters": request["parameters"],
        "features": names,
        "bounds": {param: list(limits) for param, limits in bounds.items()},
        "speedRange": list(SPEED_RANGE),
        "densityRange": list(DENSITY_RANGE),
        "baseGeometry": request["config"]["geometry"],
        "reference": request["config"]["reference"],
        "dataset": f"data/datasets/{model_id}.csv",
    }
    (MODEL_DIR / f"{model_id}.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    with _lock:
        _loaded[model_id] = TrainedSurrogate(meta=meta, models=models)
    report("POST_PROCESSING", 0.99, "Model stored")
    return meta


class MLSurrogateEngine(SimulationEngine):
    mode = "ml-surrogate"

    def availability(self) -> tuple[bool, str]:
        count = len(list_models())
        if count == 0:
            return False, "No surrogate has been trained yet. Train one from the CFD / ML tab."
        return True, f"{count} trained surrogate model{'s' if count != 1 else ''} stored."

    def simulate(self, config: dict[str, Any], report: ProgressReporter = no_progress) -> dict[str, Any]:
        report("PREPARING", 0.1, "Loading the surrogate model")
        prepared = prepare_case(config)
        surrogate = latest_model_for(config["vehicleId"])
        if surrogate is None:
            raise SimulationError(
                "SURROGATE_NOT_TRAINED",
                f'No surrogate model has been trained for the vehicle "{config["vehicleId"]}". '
                "Train one from the CFD / ML tab. Nothing was predicted.",
            )
        meta = surrogate.meta
        geometry, flow, metrics = config["geometry"], prepared.flow, prepared.metrics
        warnings: list[dict[str, str]] = []

        def warn(code: str, message: str) -> None:
            warnings.append({"code": code, "severity": "warning", "message": message})

        outside = [
            PARAM_BY_ID[param]["label"]
            for param, (low, high) in meta["bounds"].items()
            if geometry[param] < low - 1e-9 or geometry[param] > high + 1e-9
        ]
        if outside:
            warn("SURROGATE_EXTRAPOLATION", "Outside the range of the training data for: " + ", ".join(outside) + ". The prediction is not reliable there.")
        untrained = [
            PARAM_BY_ID[param]["label"]
            for param, definition in PARAM_BY_ID.items()
            if param not in meta["bounds"]
            and param != "minGroundClearance"
            and abs(geometry[param] - meta["baseGeometry"][param]) > definition["step"] * 1e-3
        ]
        if untrained:
            warn(
                "SURROGATE_UNSEEN_PARAMETER",
                "These parameters differ from the geometry the surrogate was trained around and were not varied in its data, "
                "so their effect is not represented: " + ", ".join(untrained) + ".",
            )
        if not (meta["speedRange"][0] <= flow.speed <= meta["speedRange"][1]):
            warn("SURROGATE_EXTRAPOLATION_SPEED", "The relative air speed is outside the range of the training data.")
        if not (meta["densityRange"][0] <= flow.density <= meta["densityRange"][1]):
            warn("SURROGATE_EXTRAPOLATION_DENSITY", "The air density is outside the range of the training data.")
        if abs(flow.yaw_deg) > 0.05:
            warn("SURROGATE_NO_YAW", "The surrogate was trained without crosswind; side force, yaw moment and yaw-induced drag are not included.")

        report("SOLVING", 0.5, "Predicting coefficients")
        features = np.array([[*(geometry[param] for param in meta["parameters"]), flow.density, flow.speed]])
        started = time.perf_counter()
        prediction = surrogate.selected.predict(features)[0]
        inference_ms = (time.perf_counter() - started) * 1000
        # Disagreement between the fitted algorithms: large where the data constrain this point poorly.
        others = [model.predict(features)[0] for key, model in surrogate.models.items() if key != meta["selected"]]
        disagreement = np.max(np.abs(np.array(others) - prediction), axis=0) if others else np.zeros(len(TARGETS))
        cd, cl, cl_front = (float(value) for value in prediction)
        if not math.isfinite(cd) or cd <= 0:
            raise SimulationError("INVALID_RESULT", "The surrogate predicted a non-physical drag coefficient.")

        source_model = MODEL["uncertainty"]["reducedOrder" if meta["sourceMode"] == "reduced-order" else "analytical"]
        uncertainty = {
            # Surrogate error (validation RMSE and algorithm disagreement) combined with the floor of the source model.
            "cd": math.sqrt(meta["validationRmseCd"] ** 2 + float(disagreement[0]) ** 2 + (source_model["cdRelative"] * cd) ** 2),
            "cl": math.sqrt(meta["validationRmseCl"] ** 2 + float(disagreement[1]) ** 2 + source_model["clAbsolute"] ** 2),
        }

        report("POST_PROCESSING", 0.9, "Assembling result")
        area = metrics.frontal_area
        q = dynamic_pressure(flow.density, flow.speed)
        lift = coefficient_force(q, cl, area)
        rear = compute_rear_flow(prepared.shape, area)
        warnings += sanity_warnings(geometry, metrics, rear, cd, cl, config["reference"]["cd"], flow.speed, flow.yaw_deg)
        source_label = "Mode B reduced-order" if meta["sourceMode"] == "reduced-order" else "Mode A analytical"
        return {
            "mode": self.mode,
            "source": "backend",
            "provenance": (
                f"Mode D · ML surrogate — {meta['algorithm'].lower()} trained on {meta['trainingSamples']} {source_label} results. "
                "A statistical prediction, not a physical simulation."
            ),
            "coefficients": {
                "cd": cd,
                "cl": cl,
                "clFront": cl_front,
                "clRear": cl - cl_front,
                "cs": 0.0,
                "cmYaw": 0.0,
                "cdFriction": friction_drag(metrics, flow),
                "referenceSpeed": flow.speed,
                "frontalArea": area,
            },
            "uncertainty": uncertainty,
            "forces": {
                "dynamicPressure": q,
                "drag": coefficient_force(q, cd, area),
                "lift": lift,
                "downforce": -lift,
                "side": 0.0,
                "yawMoment": 0.0,
            },
            "wind": {"relativeSpeed": flow.speed, "yawAngleDeg": flow.yaw_deg},
            "air": {
                "density": flow.density,
                "viscosity": flow.viscosity,
                "reynolds": reynolds_number(flow.density, flow.speed, metrics.length, flow.viscosity),
            },
            "breakdown": {
                "drag": [{"id": "surrogate", "label": "Predicted total (surrogate)", "value": cd}],
                "lift": [{"id": "surrogate", "label": "Predicted total (surrogate)", "value": cl}],
            },
            "calibration": {"cdRaw": cd, "clRaw": cl, "cdOffset": 0.0, "clOffset": 0.0},
            "rearFlow": rear.to_json(),
            "metrics": metrics.to_json(),
            "warnings": warnings,
            "assumptions": SURROGATE_ASSUMPTIONS,
            "surrogate": {
                "modelId": meta["modelId"],
                "algorithm": meta["algorithm"],
                "trainingSamples": meta["trainingSamples"],
                "sourceMode": meta["sourceMode"],
                "validationRmseCd": meta["validationRmseCd"],
                "validationRmseCl": meta["validationRmseCl"],
                "validationR2Cd": meta["validationR2Cd"],
                "validationR2Cl": meta["validationR2Cl"],
                "inferenceTimeMs": inference_ms,
            },
        }
