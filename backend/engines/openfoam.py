def _control_dict(prepared: PreparedCase, config: dict[str, Any], iterations: int) -> str:
    shape = prepared.shape
    yaw = prepared.flow.yaw_deg * DEG_TO_RAD
    mid = 0.5 * (shape.front_axle_x + shape.rear_axle_x)
    if prepared.surface is not None:
        patches = "(body)"
    else:
        patches = "(body wheels devices)" if device_surfaces(shape) is not None else "(body wheels)"
    return (
        _header("dictionary", "controlDict")
        + f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {iterations};
deltaT          1;
writeControl    timeStep;
writeInterval   {max(iterations // 4, 1)};
purgeWrite      2;
writeFormat     binary;
writePrecision  8;
timeFormat      general;
runTimeModifiable true;

functions
{{
    forceCoeffs
    {{
        type            forceCoeffs;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   1;
        patches         {patches};
        rho             rhoInf;
        rhoInf          {prepared.flow.density:.6f};
        // Body axes: drag along X, lift along Z. The onset flow is yawed by {prepared.flow.yaw_deg:.3f} deg.
        dragDir         (1 0 0);
        liftDir         (0 0 1);
        pitchAxis       (0 1 0);
        CofR            ({mid:.4f} 0 0);
        magUInf         {prepared.flow.speed:.6f};
        lRef            {config["geometry"]["wheelbase"]:.4f};
        Aref            {prepared.metrics.frontal_area:.6f};
    }}
    yPlus {{ type yPlus; libs (fieldFunctionObjects); writeControl writeTime; }}
}}
// freestream direction (cos, sin, 0) = ({math.cos(yaw):.6f} {math.sin(yaw):.6f} 0)
"""
    )


