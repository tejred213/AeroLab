@dataclass(frozen=True)
class CaseStep:
    """One program of a case run; its output goes to log.<label>."""

    label: str
    command: str
    #: An optional step that fails is reported, not fatal (a mesh with failed checks can still run, and says so).
    required: bool = True


def parallel(command: str, processors: int) -> str:
    return f"mpirun -np {processors} {command} -parallel" if processors > 1 else command


def case_steps(processors: int) -> list[CaseStep]:
    """The programs a case runs, in order; shared by the Allrun script and the backend's own run.

    With several processes the background mesh is decomposed before snappyHexMesh, so the meshing runs on every
    process and not only the solver (snappyHexMesh balances the load itself as it refines). The initial fields
    are copied to the processors rather than decomposed; their processor patches come from setConstraintTypes.
    """
    steps = [CaseStep("blockMesh", "blockMesh"), CaseStep("surfaceFeatures", "surfaceFeatureExtract || surfaceFeatures")]
    if processors > 1:
        steps.append(CaseStep("decomposePar", "decomposePar -force -copyZero"))
    return [
        *steps,
        CaseStep("snappyHexMesh", parallel("snappyHexMesh -overwrite", processors)),
        CaseStep("checkMesh", parallel("checkMesh", processors), required=False),
        CaseStep("simpleFoam", parallel("simpleFoam", processors)),
    ]


def _allrun(plan: CasePlan) -> str:
    lines = ["#!/bin/sh", 'cd "${0%/*}" || exit 1', "set -e"]
    for step in case_steps(plan.processors):
        command = f"({step.command})" if "||" in step.command else step.command
        lines.append(f"{command} > log.{step.label} 2>&1" + ("" if step.required else " || true"))
    return "\n".join(lines) + "\n"


def generate_case(config: dict[str, Any], prepared: PreparedCase, case_dir: Path, iterations: int | None = None) -> list[str]:
    """Writes a complete simpleFoam case for the configuration. Returns the relative file names."""
    prepared = prepare_cfd_case(config, prepared)
    shape = prepared.shape
    plan = plan_case(config, prepared)
    settings = plan.settings
    wrapped = prepared.surface is not None
    devices = None if wrapped else device_surfaces(shape)
    nu = prepared.flow.viscosity / prepared.flow.density
    turbulence = (
        _header("dictionary", "turbulenceProperties")
        + "\nsimulationType RAS;\nRAS { RASModel kOmegaSST; turbulence on; printCoeffs on; }\n"
    )
    binary: dict[str, bytes] = {}
    files: dict[str, str] = {}
    if wrapped:
        # The supplied surface, lowered so that its tyres stand in the ground; it includes the wheels.
        binary["constant/triSurface/body.stl"] = sunk_stl(load_surface(prepared.surface.id)[1])
    else:
        files["constant/triSurface/body.stl"] = to_ascii_stl("body", body_surface(shape))
        files["constant/triSurface/wheels.stl"] = to_ascii_stl("wheels", wheel_surfaces(shape))
    files |= {
        "constant/transportProperties": _header("dictionary", "transportProperties")
        + f"\ntransportModel  Newtonian;\nnu              {nu:.6e};\n",
        "constant/turbulenceProperties": turbulence,
        "constant/momentumTransport": turbulence.replace("turbulenceProperties", "momentumTransport"),
        "system/blockMeshDict": _block_mesh_dict(prepared.metrics.length, settings),
        "system/snappyHexMeshDict": _snappy_dict(prepared, devices is not None, settings),
        "system/surfaceFeatureExtractDict": _header("dictionary", "surfaceFeatureExtractDict")
        + "\nbody.stl\n{\n    extractionMethod extractFromSurface;\n    includedAngle 150;\n    writeObj no;\n}\n",
        "system/controlDict": _control_dict(prepared, config, iterations or settings.iterations),
        "system/fvSchemes": _fv_schemes(),
        "system/fvSolution": _fv_solution(),
        "system/decomposeParDict": _header("dictionary", "decomposeParDict")
        + f"\nnumberOfSubdomains {plan.processors};\nmethod scotch;\n",
        "Allrun": _allrun(plan),
        "README-AEROLAB.txt": _readme(prepared, config, plan),
        **_fields(prepared, devices is not None),
    }
    if devices is not None:
        files["constant/triSurface/devices.stl"] = to_ascii_stl("devices", devices)

    for name, content in files.items():
        path = case_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for name, data in binary.items():
        path = case_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    os.chmod(case_dir / "Allrun", 0o755)
    return sorted([*files, *binary])


def zip_case(case_dir: Path) -> Path:
    archive = case_dir.with_suffix(".zip")
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        for path in sorted(case_dir.rglob("*")):
            if path.is_file():
                bundle.write(path, Path(case_dir.name) / path.relative_to(case_dir))
    return archive


