@dataclass(frozen=True)
class Launcher:
    """How OpenFOAM programs are started on this machine."""

    #: Path of the `openfoam` session wrapper, or None when the programs are on the PATH.
    wrapper: str | None
    #: OpenFOAM version reported by the environment ("" if unknown).
    version: str
    detail: str

    def argv(self, shell_command: str) -> list[str]:
        """Argument vector that runs a shell command with the OpenFOAM environment loaded."""
        if self.wrapper is None:
            return ["sh", "-c", shell_command]
        return [self.wrapper, "-c", shell_command]


def _wrapper_candidates() -> list[str]:
    """Session wrappers to try, most specific first."""
    explicit = os.environ.get(WRAPPER_ENV)
    if explicit:
        return [explicit]
    found: list[str] = []
    on_path = shutil.which("openfoam")
    if on_path:
        found.append(on_path)
    # Versioned wrappers installed by the Linux packages (openfoam2412, ...), newest first.
    for directory in os.environ.get("PATH", "").split(os.pathsep):
        if directory:
            found += sorted(glob.glob(os.path.join(directory, "openfoam[0-9]*")), reverse=True)
    found += sorted(glob.glob(APP_WRAPPER_PATTERN), reverse=True)
    unique: list[str] = []
    for path in found:
        if path not in unique and os.access(path, os.X_OK):
            unique.append(path)
    return unique


def _probe_wrapper(wrapper: str) -> tuple[str | None, str]:
    """Asks a wrapper whether its environment has every required program.

    Returns (problem, version): problem is None when the wrapper works.
    """
    check = " && ".join(f"command -v {name} >/dev/null" for name in REQUIRED_EXECUTABLES)
    try:
        completed = subprocess.run(
            [wrapper, "-c", f'{check} && echo "AEROLAB_FOAM_VERSION=$WM_PROJECT_VERSION"'],
            capture_output=True,
            text=True,
            timeout=PROBE_TIMEOUT,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return f"{wrapper} did not answer within {PROBE_TIMEOUT:.0f} s", ""
    except OSError as error:
        return f"{wrapper} could not be started ({error.strerror or error})", ""
    match = re.search(r"AEROLAB_FOAM_VERSION=(\S*)", completed.stdout)
    if completed.returncode != 0 or match is None:
        lines = (completed.stderr or completed.stdout).strip().splitlines()
        reason = f" ({lines[-1][:160]})" if lines else ""
        return f"{wrapper} does not provide {', '.join(REQUIRED_EXECUTABLES)}{reason}", ""
    return None, match.group(1)


def _discover_launcher() -> tuple[Launcher | None, str]:
    if all(shutil.which(name) for name in REQUIRED_EXECUTABLES):
        version = os.environ.get("WM_PROJECT_VERSION", "")
        detail = f"OpenFOAM {version} executables found on PATH.".replace("  ", " ")
        return Launcher(None, version, detail), detail
    problems: list[str] = []
    for wrapper in _wrapper_candidates():
        problem, version = _probe_wrapper(wrapper)
        if problem is None:
            detail = f"OpenFOAM {version} found through its session wrapper ({wrapper}).".replace("  ", " ")
            return Launcher(wrapper, version, detail), detail
        problems.append(problem)
    detail = (
        "OpenFOAM is not available on the backend machine: "
        + ", ".join(REQUIRED_EXECUTABLES)
        + " are not on the PATH and no working `openfoam` session wrapper was found"
        + (" (" + "; ".join(problems) + ")" if problems else "")
        + f". Install OpenFOAM (on macOS: OpenFOAM.app), or set {WRAPPER_ENV} to the path of its `openfoam` script. "
        "Case generation and coefficient import still work."
    )
    return None, detail


_launcher_lock = threading.Lock()
#: (valid until, launcher, detail). A positive answer is kept longer than a negative one, so that
#: OpenFOAM installed while the backend runs is picked up without a restart.
_launcher_cache: tuple[float, Launcher | None, str] | None = None
_FOUND_SECONDS = 600.0
_MISSING_SECONDS = 20.0


def reset_launcher_cache() -> None:
    global _launcher_cache
    with _launcher_lock:
        _launcher_cache = None


def find_launcher(wait: bool = True) -> tuple[Launcher | None, str]:
    """Locates OpenFOAM (cached).

    Probing a wrapper starts it, which can take a few seconds the first time.
    With wait=False a probe that is already running elsewhere is not waited
    for: the answer is "not yet known".
    """
    global _launcher_cache
    cached = _launcher_cache
    if cached is not None and time.monotonic() < cached[0]:
        return cached[1], cached[2]
    if not _launcher_lock.acquire(blocking=wait):
        return None, "Looking for OpenFOAM on the backend machine; this takes a few seconds after start-up."
    try:
        cached = _launcher_cache
        if cached is not None and time.monotonic() < cached[0]:
            return cached[1], cached[2]
        launcher, detail = _discover_launcher()
        _launcher_cache = (time.monotonic() + (_FOUND_SECONDS if launcher else _MISSING_SECONDS), launcher, detail)
        return launcher, detail
    finally:
        _launcher_lock.release()


def solver_availability(wait: bool = False) -> tuple[bool, str]:
    launcher, detail = find_launcher(wait)
    return launcher is not None, detail


@functools.lru_cache(maxsize=1)
def _performance_cores() -> int:
    """Cores worth giving to MPI: an MPI run advances at the pace of its slowest process."""
    if sys.platform == "darwin":
        try:
            # Apple silicon: performance cores only.
            out = subprocess.run(
                ["sysctl", "-n", "hw.perflevel0.physicalcpu"], capture_output=True, text=True, timeout=5, check=False
            ).stdout.strip()
            if out.isdigit() and int(out) > 0:
                return int(out)
        except (OSError, subprocess.TimeoutExpired):
            pass
    # Elsewhere assume two hardware threads per core.
    return max(1, (os.cpu_count() or 2) // 2)


def processors_for(cells: int) -> int:
    """MPI processes for a mesh of about `cells` cells (at least ~30 000 cells per process)."""
    explicit = os.environ.get(PROCESSORS_ENV, "")
    if explicit.isdigit() and int(explicit) > 0:
        return int(explicit)
    return max(1, min(_performance_cores(), cells // 30000))


