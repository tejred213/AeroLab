def _fields(prepared: PreparedCase, has_devices: bool) -> dict[str, str]:
    flow = prepared.flow
    yaw = flow.yaw_deg * DEG_TO_RAD
    ux, uy = flow.speed * math.cos(yaw), flow.speed * math.sin(yaw)
    intensity = 0.005
    k = 1.5 * (flow.speed * intensity) ** 2
    omega = math.sqrt(max(k, 1e-12)) / (0.09**0.25 * 0.1)
    velocity = f"({ux:.6f} {uy:.6f} 0)"
    vehicle = "body|devices" if has_devices else "body"
    wrapped = prepared.surface is not None
    walls = "(body)" if wrapped else f"({vehicle}|wheels)"
    wheels = wheel_geometry(prepared.shape)
    radius = wheels[0].radius
    spin = flow.speed / radius

    def field(cls: str, name: str, dimensions: str, internal: str, patches: str) -> str:
        return (
            _header(cls, name)
            + f"\ndimensions      {dimensions};\ninternalField   uniform {internal};\n\nboundaryField\n{{\n"
            # Processor patches of a decomposed mesh (and any other constraint patches) take their own types.
            + f'    #includeEtc "caseDicts/setConstraintTypes"\n\n{patches}}}\n'
        )

    sides = '    "(top|sideLeft|sideRight)" { type slip; }\n'
    # Each wheel spins about its own axle (a line through the wheel centre, parallel to Y).
    return {
        "0/U": field(
            "volVectorField",
            "U",
            "[0 1 -1 0 0 0 0]",
            velocity,
            f"    inlet  {{ type fixedValue; value uniform {velocity}; }}\n"
            "    outlet { type inletOutlet; inletValue uniform (0 0 0); value $internalField; }\n"
            f"    ground {{ type fixedValue; value uniform {velocity}; }}\n"
            + sides
            + f'    "({vehicle})" {{ type noSlip; }}\n'
            + (
                "    // The wheels are part of the wrapped surface and are stationary.\n"
                if wrapped
                else "    // One rotating-wall condition cannot serve two axles: split the wheels patch per axle\n"
                "    // (e.g. with topoSet/createPatch) and give each its own origin. Until then the wheels are stationary.\n"
                f"    wheels {{ type noSlip; }} // rotatingWallVelocity; axis (0 1 0); omega {spin:.4f}; origins: "
                + ", ".join(f"({w.x:.4f} 0 {w.z:.4f})" for w in wheels)
                + "\n"
            ),
        ),
        "0/p": field(
            "volScalarField",
            "p",
            "[0 2 -2 0 0 0 0]",
            "0",
            "    inlet  { type zeroGradient; }\n    outlet { type fixedValue; value uniform 0; }\n    ground { type zeroGradient; }\n"
            + sides
            + f'    "{walls}" {{ type zeroGradient; }}\n',
        ),
        "0/k": field(
            "volScalarField",
            "k",
            "[0 2 -2 0 0 0 0]",
            f"{k:.6e}",
            f"    inlet  {{ type fixedValue; value uniform {k:.6e}; }}\n"
            "    outlet { type inletOutlet; inletValue $internalField; value $internalField; }\n"
            "    ground { type kqRWallFunction; value $internalField; }\n"
            + sides
            + f'    "{walls}" {{ type kqRWallFunction; value $internalField; }}\n',
        ),
        "0/omega": field(
            "volScalarField",
            "omega",
            "[0 0 -1 0 0 0 0]",
            f"{omega:.6e}",
            f"    inlet  {{ type fixedValue; value uniform {omega:.6e}; }}\n"
            "    outlet { type inletOutlet; inletValue $internalField; value $internalField; }\n"
            "    ground { type omegaWallFunction; value $internalField; }\n"
            + sides
            + f'    "{walls}" {{ type omegaWallFunction; value $internalField; }}\n',
        ),
        "0/nut": field(
            "volScalarField",
            "nut",
            "[0 2 -1 0 0 0 0]",
            "0",
            "    inlet  { type calculated; value uniform 0; }\n    outlet { type calculated; value uniform 0; }\n"
            "    ground { type nutkWallFunction; value uniform 0; }\n"
            + sides
            + f'    "{walls}" {{ type nutkWallFunction; value uniform 0; }}\n',
        ),
    }


