_COLUMN_ALIASES = {"cd": "Cd", "cl": "Cl", "cs": "Cs", "cmYaw": "CmYaw", "clFront": "Cl(f)", "clRear": "Cl(r)"}


def parse_force_coeffs(text: str) -> dict[str, Any]:
    """Parses an OpenFOAM forceCoeffs output file (coefficient.dat / forceCoeffs.dat).

    The column layout is read from the header, so both the ESI layout
    (Time Cd Cd(f) Cd(r) Cl Cl(f) Cl(r) CmPitch CmRoll CmYaw Cs ...) and older
    layouts (Time Cm Cd Cl Cl(f) Cl(r)) are accepted.
    """
    columns: list[str] | None = None
    metadata: dict[str, float] = {}
    rows: list[list[float]] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            body = stripped.lstrip("#").strip()
            match = re.match(r"^(Aref|lRef|magUInf)\s*:\s*([-+0-9.eE]+)", body)
            if match:
                metadata[match.group(1)] = float(match.group(2))
            elif body.startswith("Time"):
                columns = body.split()
            continue
        try:
            rows.append([float(token) for token in stripped.replace("(", " ").replace(")", " ").split()])
        except ValueError as error:
            raise SimulationError("CFD_PARSE_ERROR", f"Non-numeric data row in the coefficient file: {stripped[:80]!r}") from error

    if columns is None:
        raise SimulationError(
            "CFD_PARSE_ERROR", 'The file has no "# Time ..." header line; it does not look like forceCoeffs output.'
        )
    if not rows:
        raise SimulationError("CFD_PARSE_ERROR", "The coefficient file contains a header but no data rows.")
    width = len(columns)
    if any(len(row) != width for row in rows):
        raise SimulationError("CFD_PARSE_ERROR", "Data rows do not match the number of header columns.")
    data = np.asarray(rows, dtype=float)
    if not np.all(np.isfinite(data)):
        raise SimulationError("CFD_PARSE_ERROR", "The coefficient file contains non-finite values.")
    for required in ("Cd", "Cl"):
        if required not in columns:
            raise SimulationError("CFD_PARSE_ERROR", f'The coefficient file has no "{required}" column.')
    return {"columns": columns, "data": data, "metadata": metadata}


def summarize_force_coeffs(parsed: dict[str, Any], window_fraction: float = 0.2) -> dict[str, Any]:
    """Mean and scatter of each coefficient over the last part of the iteration history."""
    columns, data = parsed["columns"], parsed["data"]
    count = len(data)
    window = max(1, min(count, max(int(round(count * window_fraction)), min(count, 50))))
    tail = data[-window:]
    # The window before the averaging window, when the history is long enough to have one.
    previous = data[-2 * window : -window] if count >= 2 * window else None
    summary: dict[str, Any] = {"iterations": count, "window": window, "metadata": parsed["metadata"]}
    for key, column in _COLUMN_ALIASES.items():
        if column in columns:
            index = columns.index(column)
            values = tail[:, index]
            summary[key] = float(values.mean())
            summary[f"{key}Std"] = float(values.std())
            # Change of the mean from one window to the next: a settled solution has none.
            summary[f"{key}Drift"] = float(values.mean() - previous[:, index].mean()) if previous is not None else None
        else:
            summary[key] = None
    return summary


#: A coefficient is treated as still moving when its mean changes by more than this between two windows.
DRIFT_ABSOLUTE = 0.002
DRIFT_RELATIVE = 0.01

#: A run may stop before its iteration limit once Cd and Cl move by less than this share of the drift
#: threshold between the last two averaging windows, and not before this share of the limit.
SETTLED_SHARE_OF_DRIFT = 0.25
SETTLED_MIN_SHARE_OF_LIMIT = 0.5
SETTLED_CHECK_EVERY = 10


def coefficients_settled(summary: dict[str, Any]) -> bool:
    """True when the averaged Cd and Cl no longer change from one window to the next (see summarize_force_coeffs)."""
    for key in ("cd", "cl"):
        mean, drift = summary.get(key), summary.get(f"{key}Drift")
        if mean is None or drift is None:
            return False
        if abs(drift) > SETTLED_SHARE_OF_DRIFT * max(DRIFT_ABSOLUTE, DRIFT_RELATIVE * abs(mean)):
            return False
    return True


def early_stop_enabled() -> bool:
    return os.environ.get(EARLY_STOP_ENV, "1").strip().lower() not in ("0", "false", "no")


def _coefficient_files(case_dir: Path) -> list[Path]:
    return sorted(case_dir.glob("postProcessing/forceCoeffs/*/coefficient*.dat")) or sorted(
        case_dir.glob("postProcessing/forceCoeffs/*/forceCoeffs*.dat")
    )


def _settled_so_far(case_dir: Path) -> bool:
    """Reads the coefficient history the running solver has written so far."""
    files = _coefficient_files(case_dir)
    if not files:
        return False
    lines = files[-1].read_text(encoding="utf-8", errors="replace").splitlines()
    # The last line may be half written.
    try:
        return coefficients_settled(summarize_force_coeffs(parse_force_coeffs("\n".join(lines[:-1]))))
    except SimulationError:
        return False


def _stop_solver(case_dir: Path) -> None:
    """Asks simpleFoam to write and stop after the current iteration (it re-reads controlDict every iteration)."""
    control = case_dir / "system/controlDict"
    text = control.read_text(encoding="utf-8")
    control.write_text(re.sub(r"^stopAt\s+\w+;", "stopAt          writeNow;", text, count=1, flags=re.MULTILINE), encoding="utf-8")


def result_from_coefficients(
    config: dict[str, Any], prepared: PreparedCase, summary: dict[str, Any], provenance: str, source: str = "backend"
) -> dict[str, Any]:
    """Builds the AeroResult JSON for coefficients read from solver output.

    `source` is "backend" when this process ran the solver and "imported" when
    the coefficients came from a file supplied by the user.

    CFD coefficients are reported as read: no calibration offset is applied.
    If the file's reference area or speed differ from the simulator's, the
    coefficients are re-referenced and a warning says so.
    """
    metrics, flow = prepared.metrics, prepared.flow
    area = metrics.frontal_area
    warnings: list[dict[str, str]] = []
    scale = 1.0
    file_area = summary["metadata"].get("Aref")
    if file_area and abs(file_area - area) / area > 0.005:
        scale *= file_area / area
        warnings.append(
            {
                "code": "CFD_REFERENCE_AREA",
                "severity": "warning",
                "message": f"The file uses Aref = {file_area:.4f} m^2; coefficients were re-referenced to the simulator's frontal area {area:.4f} m^2.",
            }
        )
    file_speed = summary["metadata"].get("magUInf")
    if file_speed and flow.speed > 0 and abs(file_speed - flow.speed) / flow.speed > 0.005:
        scale *= (file_speed / flow.speed) ** 2
        warnings.append(
            {
                "code": "CFD_REFERENCE_SPEED",
                "severity": "warning",
                "message": f"The file uses magUInf = {file_speed:.3f} m/s but the configured relative air speed is {flow.speed:.3f} m/s; coefficients were re-referenced. The run may not correspond to these conditions.",
            }
        )

    cd = summary["cd"] * scale
    cl = summary["cl"] * scale
    cs = (summary["cs"] or 0.0) * scale
    cm_yaw = (summary["cmYaw"] or 0.0) * scale
    if not (math.isfinite(cd) and math.isfinite(cl)) or cd <= 0:
        raise SimulationError("INVALID_RESULT", f"The CFD output gives a non-physical drag coefficient (Cd = {cd:.4f}).")
    if summary["clFront"] is not None and summary["clRear"] is not None:
        cl_front = summary["clFront"] * scale
    else:
        cl_front = 0.5 * cl
        warnings.append(
            {
                "code": "CFD_NO_AXLE_SPLIT",
                "severity": "warning",
                "message": "The file has no Cl(f) / Cl(r) columns; lift is split equally between the axles for the performance model.",
            }
        )
    if summary["iterations"] < 200:
        warnings.append(
            {
                "code": "CFD_FEW_ITERATIONS",
                "severity": "warning",
                "message": f"Only {summary['iterations']} iterations in the file; the solution may not be converged.",
            }
        )
    drift_cd = (summary.get("cdDrift") or 0.0) * scale
    drift_cl = (summary.get("clDrift") or 0.0) * scale
    if abs(drift_cd) > max(DRIFT_ABSOLUTE, DRIFT_RELATIVE * abs(cd)) or abs(drift_cl) > max(DRIFT_ABSOLUTE, DRIFT_RELATIVE * abs(cl)):
        warnings.append(
            {
                "code": "CFD_NOT_SETTLED",
                "severity": "warning",
                "message": (
                    f"The coefficients are still changing: between the last two averaging windows Cd moved by {drift_cd:+.4f} "
                    f"and Cl by {drift_cl:+.4f}. The solution has not settled; run more iterations before using these values."
                ),
            }
        )

    rear = compute_rear_flow(prepared.shape, area)
    q = dynamic_pressure(flow.density, flow.speed)
    lift = coefficient_force(q, cl, area)
    warnings += sanity_warnings(config["geometry"], metrics, rear, cd, cl, config["reference"]["cd"], flow.speed, flow.yaw_deg)
    return {
        "mode": "cfd",
        "source": source,
        "provenance": provenance,
        "coefficients": {
            "cd": cd,
            "cl": cl,
            "clFront": cl_front,
            "clRear": cl - cl_front,
            "cs": cs,
            "cmYaw": cm_yaw,
            # Reynolds dependence is not known from one CFD point: Cd is held constant with speed.
            "cdFriction": 0.0,
            "referenceSpeed": flow.speed,
            "frontalArea": area,
        },
        # Iteration scatter over the averaging window and drift between windows. It excludes discretisation
        # and turbulence-model error.
        "uncertainty": {
            "cd": math.hypot(2 * (summary["cdStd"] or 0.0) * scale, drift_cd),
            "cl": math.hypot(2 * (summary["clStd"] or 0.0) * scale, drift_cl),
        },
        "forces": {
            "dynamicPressure": q,
            "drag": coefficient_force(q, cd, area),
            "lift": lift,
            "downforce": -lift,
            "side": coefficient_force(q, cs, area),
            "yawMoment": coefficient_force(q, cm_yaw, area) * config["geometry"]["wheelbase"],
        },
        "wind": {"relativeSpeed": flow.speed, "yawAngleDeg": flow.yaw_deg},
        "air": {
            "density": flow.density,
            "viscosity": flow.viscosity,
            "reynolds": reynolds_number(flow.density, flow.speed, metrics.length, flow.viscosity),
        },
        "breakdown": {
            "drag": [{"id": "cfd", "label": "Total from CFD (forceCoeffs)", "value": cd}],
            "lift": [{"id": "cfd", "label": "Total from CFD (forceCoeffs)", "value": cl}],
        },
        "calibration": {"cdRaw": cd, "clRaw": cl, "cdOffset": 0.0, "clOffset": 0.0},
        "rearFlow": rear.to_json(),
        "metrics": metrics.to_json(),
        "warnings": warnings,
        "assumptions": CFD_ASSUMPTIONS
        + [
            f"Averaged over the last {summary['window']} of {summary['iterations']} iterations; ± combines twice the scatter "
            "in that window with the change of the mean from the window before it."
        ],
    }


