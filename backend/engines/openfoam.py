def _terminate(process: "subprocess.Popen[str]") -> None:
    """Stops a step and everything it started (the wrapper, mpirun and the solver processes)."""
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        process.kill()


class OpenFOAMEngine(SimulationEngine, CFDBackend):
    mode = "cfd"
    provenance = RUN_PROVENANCE

    def __init__(self) -> None:
        self._case_dir: Path | None = None
        self._report: ProgressReporter = no_progress
        self._run_info: dict[str, Any] | None = None

    def availability(self) -> tuple[bool, str]:
        return solver_availability()

    def case_dir_for(self, config: dict[str, Any]) -> Path:
        return CASES_DIR / f"case-{hash_config(config)}"

    def prepare_case_files(self, config: dict[str, Any], prepared: PreparedCase | None = None) -> tuple[Path, list[str], PreparedCase]:
        prepared = prepare_cfd_case(config, prepared)
        case_dir = self.case_dir_for(config)
        if case_dir.exists():
            shutil.rmtree(case_dir)
        files = generate_case(config, prepared, case_dir)
        self._case_dir = case_dir
        self._run_info = None
        return case_dir, files, prepared

    # -- CFDBackend ---------------------------------------------------------

    def run(self, geometry: dict[str, float], conditions: dict[str, Any]) -> None:
        """Generates the case for `geometry` under `conditions` (a simulation config) and runs OpenFOAM."""
        launcher, detail = find_launcher()
        if launcher is None:
            raise SimulationError("CFD_SOLVER_UNAVAILABLE", f"{detail} No CFD result was produced.")
        config = {**conditions, "geometry": geometry}
        case_dir, _, prepared = self.prepare_case_files(config)
        plan = plan_case(config, prepared)
        started = time.monotonic()
        deadline = started + float(os.environ.get(TIMEOUT_ENV, 6 * 3600))

        *mesh_steps, solve = case_steps(plan.processors)
        on = f" on {plan.processors} processes" if plan.processors > 1 else ""
        messages = {
            "decomposePar": f"Decomposing for {plan.processors} processes",
            "snappyHexMesh": f"Running snappyHexMesh{on}",
            "checkMesh": "Checking the mesh",
        }
        for index, step in enumerate(mesh_steps):
            self._report("MESHING", 0.03 + 0.14 * index / len(mesh_steps), messages.get(step.label, f"Running {step.label}"))
            self._step(launcher, step.command, case_dir, step.label, deadline, required=step.required)
        cells, failed_checks = _read_check_mesh(case_dir / "log.checkMesh")

        iterations = plan.settings.iterations
        last_iteration = 0
        settled_at: int | None = None
        watch = early_stop_enabled()

        def on_line(line: str) -> None:
            nonlocal last_iteration, settled_at
            match = re.match(r"^Time = (\d+)", line)
            if match:
                last_iteration = int(match.group(1))
                self._report(
                    "SOLVING",
                    0.18 + 0.77 * min(last_iteration / iterations, 1.0),
                    f"simpleFoam · iteration {last_iteration} of at most {iterations}",
                )
                if (
                    watch
                    and settled_at is None
                    and last_iteration >= SETTLED_MIN_SHARE_OF_LIMIT * iterations
                    and last_iteration % SETTLED_CHECK_EVERY == 0
                    and _settled_so_far(case_dir)
                ):
                    settled_at = last_iteration
                    _stop_solver(case_dir)
                    self._report("SOLVING", 0.18 + 0.77 * last_iteration / iterations, f"Cd and Cl settled at iteration {last_iteration}; stopping")

        self._report("SOLVING", 0.18, "Starting simpleFoam")
        self._step(launcher, solve.command, case_dir, solve.label, deadline, on_line=on_line)
        self._run_info = {
            "yPlusBody": _read_y_plus(case_dir / "log.simpleFoam", "body"),
            "openfoamVersion": launcher.version,
            "meshSetting": plan.fidelity,
            "cells": cells,
            "meshChecksFailed": failed_checks,
            "prismLayers": plan.settings.layers,
            "surfaceCellMm": [round(plan.settings.size(level) * 1000, 1) for level in plan.settings.body_levels],
            "processors": plan.processors,
            "iterations": last_iteration,
            "iterationLimit": iterations,
            # Before the limit, simpleFoam stops by itself only when every residual target is met.
            "residualTargetsMet": settled_at is None and 0 < last_iteration < iterations,
            # Iteration at which the backend stopped the solver because the coefficients had settled.
            "settledAt": settled_at,
            "wallTimeS": time.monotonic() - started,
            "caseDir": str(case_dir),
        }

    def get_results(self) -> dict[str, Any]:
        if self._case_dir is None:
            raise SimulationError("CFD_NO_CASE", "No CFD case has been run.")
        candidates = _coefficient_files(self._case_dir)
        if not candidates:
            raise SimulationError(
                "CFD_NO_RESULTS", "The solver finished without writing forceCoeffs output; see the logs in the case directory."
            )
        return summarize_force_coeffs(parse_force_coeffs(candidates[-1].read_text(encoding="utf-8")))

    # -- helpers --------------------------------------------------------------

    def _step(
        self,
        launcher: Launcher,
        command: str,
        case_dir: Path,
        label: str,
        deadline: float,
        on_line: Callable[[str], None] | None = None,
        required: bool = True,
    ) -> None:
        """Runs one OpenFOAM step in the case directory, writing its output to log.<label>."""
        log = case_dir / f"log.{label}"
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise SimulationError("TIMEOUT", f"The time limit of the CFD run was reached before {label} could start.")
        timed_out = threading.Event()
        try:
            process = subprocess.Popen(
                launcher.argv(command),
                cwd=case_dir,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                errors="replace",
                # Its own process group, so that a time-out stops the solver processes too.
                start_new_session=True,
            )
        except OSError as error:
            raise SimulationError("CFD_SOLVER_UNAVAILABLE", f"Could not start {label}: {error}") from error

        def expire() -> None:
            timed_out.set()
            _terminate(process)

        watchdog = threading.Timer(remaining, expire)
        watchdog.start()
        try:
            assert process.stdout is not None
            with open(log, "w", encoding="utf-8") as handle:
                for line in process.stdout:
                    handle.write(line)
                    if on_line is not None:
                        on_line(line)
            code = process.wait()
        finally:
            watchdog.cancel()
        if timed_out.is_set():
            raise SimulationError("TIMEOUT", f"{label} was stopped because the CFD run exceeded its time limit; see {log}.")
        if code != 0 and required:
            raise SimulationError("CFD_SOLVER_FAILED", f"{label} failed with exit code {code}; see {log}.{_log_tail(log)}")

    # -- SimulationEngine -----------------------------------------------------

    def simulate(self, config: dict[str, Any], report: ProgressReporter = no_progress) -> dict[str, Any]:
        check_run_fidelity(config)
        report("PREPARING", 0.0, "Checking the CFD solver")
        launcher, detail = find_launcher()
        if launcher is None:
            # No fallback to another model here: a Mode C request either returns CFD or fails.
            raise SimulationError("CFD_SOLVER_UNAVAILABLE", f"{detail} No CFD result was produced.")
        prepared = prepare_cfd_case(config)
        self._report = report
        report("PREPARING", 0.02, "Generating the OpenFOAM case")
        self.run(config["geometry"], config)
        report("POST_PROCESSING", 0.97, "Parsing force coefficients")
        result = result_from_coefficients(config, prepared, self.get_results(), self.provenance)
        result = describe_run(result, self._run_info or {})
        if prepared.surface is not None:
            describe_surface(result, prepared.surface, config["cfdSurface"])
        return result


def _log_tail(log: Path, lines: int = 3) -> str:
    """The last lines of a step's log, for the error message."""
    try:
        tail = [line.strip() for line in log.read_text(encoding="utf-8", errors="replace").splitlines() if line.strip()][-lines:]
    except OSError:
        return ""
    return " Last output: " + " | ".join(line[:200] for line in tail) if tail else ""


def _read_check_mesh(log: Path) -> tuple[int | None, int | None]:
    """(cell count, number of failed mesh checks) from a checkMesh log; None where it cannot be read."""
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None, None
    cells = re.search(r"^\s*cells:\s+(\d+)", text, re.MULTILINE)
    failed = re.search(r"Failed (\d+) mesh checks", text)
    passed = "Mesh OK" in text
    return (int(cells.group(1)) if cells else None), (int(failed.group(1)) if failed else 0 if passed else None)


def _read_y_plus(log: Path, patch: str) -> dict[str, float] | None:
    """Last y+ report of the yPlus function object for a patch; None if the log has none."""
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    number = r"([-+0-9.eE]+)"
    found = re.findall(rf"patch {re.escape(patch)} y\+ : min = {number}, max = {number}, average = {number}", text)
    if not found:
        return None
    low, high, average = (float(value) for value in found[-1])
    return {"min": low, "max": high, "average": average}


#: Range of y+ in which the wall functions used by the generated case are meant to work.
WALL_FUNCTION_Y_PLUS = (30.0, 300.0)


def describe_surface(result: dict[str, Any], surface: SurfaceInfo, reference: dict[str, Any]) -> None:
    """Says, on a result computed on a supplied surface, what that surface is and is not."""
    voxel = reference.get("voxel")
    seal = reference.get("seal")
    detail = f"down to about {voxel * 1000:.0f} mm" if voxel else "down to the size of the wrapping grid"
    gaps = f", gaps under {seal * 1000:.0f} mm sealed" if seal else ", narrow gaps sealed"
    message = (
        f"This is CFD of the imported 3D model after shrink-wrapping: one closed surface ({surface.triangles:,} triangles) "
        f"that follows the model {detail}{gaps}. It has the model's mirrors, wheels and wheel arches, but no cooling flow, "
        f"stationary wheels, and tyres sunk {SURFACE_SINK * 1000:.0f} mm into the ground. Parameter changes made in the editor are "
        "not in it. The accuracy of the model itself is not verified, and Mode C applies no class-reference calibration, so "
        "its coefficients are not directly comparable with Modes A and B."
    )
    for warning in result["warnings"]:
        if warning["code"] == "CFD_SIMPLIFIED_GEOMETRY":
            warning["code"] = "CFD_WRAPPED_GEOMETRY"
            warning["message"] = message
            break
    else:
        result["warnings"].append({"code": "CFD_WRAPPED_GEOMETRY", "severity": "info", "message": message})
    result["provenance"] = result["provenance"].replace(
        "generated from the parametric geometry", "generated from the shrink-wrapped surface of the imported 3D model"
    )
    result.setdefault("cfd", {})["surface"] = {**surface.to_json(), "voxel": voxel, "seal": seal}


def describe_run(result: dict[str, Any], run: dict[str, Any]) -> dict[str, Any]:
    """Adds what is known about the solver run to a CFD result: mesh, convergence and the caveats they imply."""
    if not run:
        return result
    warnings = result["warnings"]

    def warn(code: str, message: str) -> None:
        warnings.append({"code": code, "severity": "warning", "message": message})

    cells = f"{run['cells']:,} cells" if run.get("cells") else "cell count not read"
    version = f" {run['openfoamVersion']}" if run.get("openfoamVersion") else ""
    result["provenance"] = (
        f"Mode C · CFD — OpenFOAM{version} simpleFoam (steady RANS, k-omega SST) run by the AeroLab backend on a "
        f"snappyHexMesh grid generated from the parametric geometry ({run['meshSetting']} mesh setting, {cells})."
    )
    if run.get("prismLayers") == 0:
        warn(
            "CFD_COARSE_MESH",
            f"Coarse mesh setting: surface cells of {run['surfaceCellMm'][0]:.0f} to {run['surfaceCellMm'][1]:.0f} mm and no "
            "prism layers, so the boundary layer is not resolved. This run shows that the CFD pipeline works; "
            "its coefficients are not mesh-converged and should not be quoted.",
        )
    if run.get("meshChecksFailed"):
        warn(
            "CFD_MESH_QUALITY",
            f"checkMesh reported {run['meshChecksFailed']} failed mesh check(s); see log.checkMesh in the case directory. "
            "Poor cells can distort the forces.",
        )
    elif run.get("meshChecksFailed") is None:
        warn("CFD_MESH_UNCHECKED", "The mesh quality report (checkMesh) could not be read; the mesh was not verified.")
    y_plus = run.get("yPlusBody")
    if y_plus and not (WALL_FUNCTION_Y_PLUS[0] <= y_plus["average"] <= WALL_FUNCTION_Y_PLUS[1]):
        warn(
            "CFD_Y_PLUS",
            f"Average y+ on the body is {y_plus['average']:.0f} (range {y_plus['min']:.0f} to {y_plus['max']:.0f}); the wall "
            f"functions are meant for about {WALL_FUNCTION_Y_PLUS[0]:.0f} to {WALL_FUNCTION_Y_PLUS[1]:.0f}. Wall shear, and with it "
            "friction drag and the separation location, are poorly predicted on this mesh.",
        )
    warnings.append(
        {
            "code": "CFD_SIMPLIFIED_GEOMETRY",
            "severity": "info",
            "message": (
                "This is CFD of the simplified parametric shape: smooth floor, no wheel arches, cooling flow or mirrors, "
                "stationary wheels. Modes A and B add a class-reference calibration for that missing detail and Mode C "
                "does not, so its coefficients are not directly comparable with theirs or with a production car."
            ),
        }
    )
    if not run.get("iterations"):
        warn("CFD_ITERATIONS_UNKNOWN", "The number of solver iterations could not be read from the solver log.")
    elif run.get("settledAt"):
        warn(
            "CFD_RESIDUALS",
            f"The run was stopped at iteration {run['settledAt']} of at most {run['iterationLimit']} because Cd and Cl had "
            "settled (their averages changed by less than a quarter of the drift threshold between the last two windows). "
            "The residual targets were not reached, so the solution is not converged in the strict sense.",
        )
    elif not run.get("residualTargetsMet"):
        warn(
            "CFD_RESIDUALS",
            f"The solver used all {run['iterationLimit']} iterations without reaching its residual targets. "
            "That is common for separated car flows, but the solution is not converged in the strict sense.",
        )
    result["cfd"] = run
    result["assumptions"] = result["assumptions"] + [
        "Mesh resolution has not been checked for mesh independence: a finer mesh may give different coefficients."
    ]
    return result
