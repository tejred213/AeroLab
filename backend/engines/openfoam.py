"""Mode C — OpenFOAM adapter.

Pipeline (each step is a method, so another solver can reuse the structure):

    1. generate geometry          geometry/stl.py -> constant/triSurface/*.stl
    2. generate mesh settings     blockMeshDict, snappyHexMeshDict
    3. create boundary conditions 0/U, p, k, omega, nut
    4. generate the case          controlDict (with forceCoeffs), schemes, solution, Allrun
    5. run the solver             blockMesh, snappyHexMesh, simpleFoam (only if installed)
    6. parse results              postProcessing/forceCoeffs/*/coefficient.dat
    7. extract Cd, Cl, Cs, CmYaw
    8. return structured results

The adapter never reports numbers it did not read from solver output. When
OpenFOAM is not installed, `simulate` raises CFD_SOLVER_UNAVAILABLE; the case can
still be generated for running elsewhere, and coefficients from such a run can
be imported with `result_from_coefficients`.

Finding OpenFOAM. The programs are used directly when they are on the PATH (a
shell where OpenFOAM's bashrc was sourced). Otherwise they are run through
OpenFOAM's session wrapper, the `openfoam` script, which loads the environment
for one command; this is the only route offered by the native macOS build
(OpenFOAM.app). Environment variables:

    AEROLAB_OPENFOAM     path of the `openfoam` wrapper to use
    AEROLAB_CFD_PROCS    number of MPI processes for the solve
    AEROLAB_CFD_TIMEOUT  time limit of one run, seconds (default 6 hours)

Mesh resolution follows the simulation's grid setting (coarse / medium / fine).
The coarse setting exists to check the pipeline quickly; it is not a mesh to
quote numbers from, and its results carry a warning that says so.

Written for the OpenFOAM.com (ESI) releases v2206 and later. The dictionaries
that differ in the OpenFOAM Foundation releases are noted in the case README.
"""

