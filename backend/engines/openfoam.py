@dataclass(frozen=True)
class MeshSettings:
    """Resolution of the generated mesh. A refinement level halves the cell size."""

    #: Background (far-field) cell size, m.
    cell: float
    #: Level in the box around the vehicle and in the wake box.
    near_level: int
    wake_level: int
    #: (min, max) level on the body surface; max is used at edges and curvature.
    body_levels: tuple[int, int]
    wheel_level: int
    #: Prism layers on the body (0 = none: the boundary layer is then not resolved at all).
    layers: int
    #: Solver iterations.
    iterations: int

    def size(self, level: int) -> float:
        return self.cell / 2**level


MESH_SETTINGS: dict[str, MeshSettings] = {
    # Surface cells of 40 / 20 mm, no prism layers: a quick check that the pipeline runs.
    "coarse": MeshSettings(cell=0.64, near_level=2, wake_level=3, body_levels=(4, 5), wheel_level=5, layers=0, iterations=500),
    # Surface cells of 31 / 16 mm with two prism layers.
    "medium": MeshSettings(cell=0.5, near_level=2, wake_level=3, body_levels=(4, 5), wheel_level=5, layers=2, iterations=1000),
    # Surface cells of 16 / 8 mm with three prism layers.
    "fine": MeshSettings(cell=0.5, near_level=3, wake_level=4, body_levels=(5, 6), wheel_level=6, layers=3, iterations=1500),
}


